import psutil
import pyautogui
import pytesseract

from core.storage import get_user_data, set_user_data, get_saved_settings
from core.ai_abacus import ai_abacus
from services.ErrorLogService import add_log_entry
from services.WhatsAppService import send_message

pytesseract.pytesseract.tesseract_cmd = r"\Tesseract-OCR\tesseract.exe"
AI_DISCLAIMER = "\n\n(This message was generated by AI. This message might contain mistakes or errors.)"

DEFAULT_REGIONS = {
    "chat_header": (400, 60, 620, 40),
    "last_message": (400, 950, 670, 130),
}

def is_running():
    return any("whatsapp" in (p.info.get("name") or "").lower() for p in psutil.process_iter(["name"]))


def get_region(name):
    settings = get_saved_settings()
    regions = settings.get("whatsapp_autoreply_regions", {})
    return tuple(regions.get(name, DEFAULT_REGIONS[name]))


def capture_region(region):
    return pyautogui.screenshot(region=region)


def ocr_text(image, debug_name="debug"):
    image.save(f"data/ocr_debug_{debug_name}.png")
    print(f"[Auto-reply] OCRing image of size {image.size}")
    return pytesseract.image_to_string(image).strip()


def get_active_chat_name():
    return ocr_text(capture_region(get_region("chat_header")))


def get_last_message_text():
    return ocr_text(capture_region(get_region("last_message")))


def already_replied_to(message_text):
    data = get_user_data()
    return data.get("whatsapp_autoreply_last_seen") == message_text


def mark_replied_to(message_text):
    set_user_data("whatsapp_autoreply_last_seen", message_text)


def generate_ai_reply(incoming_text):
    text_prompt = "You are auto-replying to a WhatsApp message. This is the last message received:\n\n" + incoming_text + ".\n\nGenerate a concise, polite, and helpful reply. DO NOT include any [COMMAND:] blocks in your reply. Your task is to generate a human-like response to the incoming message. Keep it short and relevant. DO not add any other explanation to the reply. Only reply to the text message received. Keep the message human, do not make it weird or robotic. Only generate the text of the reply itself. Also make sure to filter out the name that might be included at the start of the string of the message you might recieve. AT THE END MIGHT BE A TIMESTAMP OF THE MESSAGE SO BE CAREFUL. Do not include any greetings or salutations in your reply. Only reply to the content of the message received. DO NOT include any [COMMAND:] blocks in your reply. Your task is to generate a human-like response to the incoming message."
    reply = ai_abacus.chat(text_prompt)
    return reply.rstrip() + AI_DISCLAIMER


def check_and_autoreply():
    # Turned off for security reasons
    return
    settings = get_saved_settings()

    if not settings.get("whatsapp_autoreply_enabled", True):
        return
    if not is_running():
        return

    target_chat = (settings.get("whatsapp_autoreply_target_chat")).strip()
    if not target_chat:
        return

    active_chat = get_active_chat_name()
    if target_chat.lower() not in active_chat.lower() or target_chat.lower() not in active_chat.lower():
        print(f"[Auto-reply] Active chat '{active_chat}' does not match target chat '{target_chat}'. Skipping auto-reply.")
        print(f"[Auto-reply] Active chat does not match target chat. Skipping auto-reply.")
        return

    incoming = get_last_message_text()
    print(f"[Auto-reply] Incoming message: {incoming!r}")
    if not incoming or already_replied_to(incoming):
        return

    try:
        reply = generate_ai_reply(incoming)
    except Exception as e:
        print(f"Auto-reply generation failed: {e}")
        add_log_entry("Auto-reply generation failed", str(e), type(e).__name__)
        return

    print(f"[Auto-reply | {active_chat}] incoming: {incoming!r}")
    print(f"[Auto-reply | {active_chat}] generated reply: {reply!r}")
    add_log_entry(
        title="WhatsApp auto-reply generated",
        description=f"Chat: {active_chat}\nIncoming: {incoming}\nReply: {reply}",
        level="INFO",
    )

    send_message(target_chat, reply)
    mark_replied_to(incoming)